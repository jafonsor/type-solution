// Writes languages/purescript/source-hashes.json: the Nix hash of each pinned
// library's GitHub archive at its pinned commit (purs-bundle.nix fetches the
// sources with them). Re-run after changing packages.json:
//   node tools/purs-bundle/prefetch-hashes.mjs
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = join(dirname(fileURLToPath(import.meta.url)), "../../languages/purescript");
const pinned = JSON.parse(readFileSync(join(dir, "packages.json"), "utf8"));
const out = { about: "Nix hashes of the GitHub archives of the libraries in packages.json at their commits. Generated by tools/purs-bundle/prefetch-hashes.mjs; purs-bundle.nix fails if it disagrees with packages.json.", libraries: {} };
for (const lib of pinned.libraries) {
  const [, owner, repo] = /github\.com\/([^/]+)\/([^/]+)$/.exec(lib.repo);
  const url = `https://github.com/${owner}/${repo}/archive/${lib.commit}.tar.gz`;
  const res = JSON.parse(execFileSync("nix", ["store", "prefetch-file", "--unpack", "--json", url], { encoding: "utf8" }));
  out.libraries[lib.name] = { owner, repo, commit: lib.commit, hash: res.hash };
  console.error(lib.name, res.hash);
}
writeFileSync(join(dir, "source-hashes.json"), JSON.stringify(out, null, 1) + "\n");
